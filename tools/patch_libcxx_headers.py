#!/usr/bin/env python3
"""Copy two of the NDK's libc++ headers into <outdir> with Apple's arm64 ABI choices
in the places where bionic's differ, so the runtime's std::__1 build matches what
guest code compiled against Apple's libc++ expects:
  <__locale>: ctype_base as on Darwin (32-bit masks, <runetype.h> _CTYPE_* bits);
              guest code reads ctype<char>'s table inline.
  <regex>:    regex_traits::char_class_type is ctype_base::mask (bionic: uint16_t).
Files are only rewritten when their contents change.
usage: patch_libcxx_headers.py <ndk-libcxx-include-dir> <outdir>"""
import pathlib, re, sys
inc, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
APPLE_CTYPE = """#if defined(_LIBCPP_PROVIDES_DEFAULT_RUNE_TABLE)
  // iosrt: Apple's ctype_base (Darwin <runetype.h> _CTYPE_* bits)
  typedef __UINT32_TYPE__ mask;
  static const mask space  = 0x00004000;
  static const mask print  = 0x00040000;
  static const mask cntrl  = 0x00000200;
  static const mask upper  = 0x00008000;
  static const mask lower  = 0x00001000;
  static const mask alpha  = 0x00000100;
  static const mask digit  = 0x00000400;
  static const mask punct  = 0x00002000;
  static const mask xdigit = 0x00010000;
  static const mask blank  = 0x00020000;
  static const mask __regex_word = 0x80;
#elif defined(__GLIBC__)"""
patches = {
    "__locale": (r"#if defined\(_LIBCPP_PROVIDES_DEFAULT_RUNE_TABLE\)\n  typedef unsigned long mask;.*?#elif defined\(__GLIBC__\)", APPLE_CTYPE),
    "regex": (r"#if defined\(__BIONIC__\) \|\| defined\(_NEWLIB_VERSION\)\n(  // Originally bionic)", r"#if 0 // iosrt: Apple's char_class_type\n\1"),
}
out.mkdir(parents=True, exist_ok=True)
for name, (pat, repl) in patches.items():
    text = (inc / name).read_text()
    new, n = re.subn(pat, lambda m: m.expand(repl) if "\\1" in repl else repl, text, count=1, flags=re.S)
    if n != 1:
        sys.exit(f"patch_libcxx_headers.py: pattern not found in {name}")
    new = f"// generated by tools/patch_libcxx_headers.py from the NDK's <{name}>\n" + new
    dst = out / name
    if not dst.exists() or dst.read_text() != new:
        dst.write_text(new)
