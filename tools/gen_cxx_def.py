#!/usr/bin/env python3
"""Generate runtime/src/exports/cxx_gen.def from the symbols defined by the
runtime's C++ support objects (std::__1 ABI functions). Mach-O names carry one
more leading underscore than the ELF names."""
import re, subprocess, sys, pathlib
nm, out, *objs = sys.argv[1:]
manual = set()
for f in pathlib.Path(out).parent.glob("*.def"):
    if f.name != pathlib.Path(out).name:
        manual |= set(re.findall(r"SYM\(\s*\w[\w+]*\s*,\s*([\w$]+)", f.read_text()))
syms = set()
for o in objs:
    for line in subprocess.run([nm, "--defined-only", "--extern-only", o], capture_output=True, text=True, check=True).stdout.splitlines():
        parts = line.split()
        if len(parts) == 3 and parts[1] in "TDRVWB" and parts[2].startswith("_Z"):
            syms.add(parts[2])
lines = ["/* generated by tools/gen_cxx_def.py from the objects in runtime/src/cxx (do not edit) */"]
for s in sorted(syms):
    if "_" + s in manual:
        continue
    lines.append(f"SYM(libc++, _{s}, {s})")
text = "\n".join(lines) + "\n"
p = pathlib.Path(out)
if not p.exists() or p.read_text() != text:
    p.write_text(text)
    print(f"updated {out}: {len(lines) - 1} symbols")
