#!/usr/bin/env python3
"""Regenerate runtime/src/exports/uikit.def from the UIKit/CoreGraphics/
QuartzCore/CoreText HLE sources: every top-level `iosrt_<Symbol>` definition
becomes an export (functions by address, variables by &address) and every
RT_DEFINE_CLASS becomes a class export. Usage: tools/gen_uikit_def.py"""
import pathlib, re, sys

root = pathlib.Path(__file__).resolve().parent.parent
src = root / "runtime/src/uikit"
out = root / "runtime/src/exports/uikit.def"
PRIVATE_CLASSES = {"UIButtonContent", "UINibDecoder", "UIRuntimeConnection", "UIRuntimeOutletConnection",
                   "UIRuntimeEventConnection", "UIRuntimeOutletCollectionConnection", "UIProxyObject"}

def lib_for(name):
    n = name.lstrip("k")
    if n.startswith("CG"): return "CoreGraphics"
    if n.startswith("CA"): return "QuartzCore"
    if n.startswith("CT"): return "CoreText"
    return "UIKit"

funcs, data, classes = {}, {}, {}
def strip(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    text = re.sub(r"//[^\n]*", " ", text)
    text = re.sub(r'"(\\.|[^"\\])*"', '""', text)
    text = re.sub(r"'(\\.|[^'\\])*'", "''", text)
    return "\n".join(l for l in text.splitlines() if not l.lstrip().startswith("#"))
def top_level_chunks(text):
    """yield (declaration text, terminator) for every top-level statement"""
    depth, cur, i = 0, [], 0
    while i < len(text):
        ch = text[i]
        if depth == 0 and ch in ";{":
            yield "".join(cur).strip(), ch
            cur = []
            if ch == "{":
                depth = 1; i += 1
                while i < len(text) and depth:
                    if text[i] == "{": depth += 1
                    elif text[i] == "}": depth -= 1
                    i += 1
                # a braced initializer continues until ';'
                continue
        else:
            cur.append(ch)
        i += 1
for f in sorted(src.glob("*.c")):
    raw = f.read_text()
    for c in re.findall(r"RT_DEFINE_CLASS\((\w+)\)", raw):
        if not c.endswith("Impl") and c not in PRIVATE_CLASSES:
            classes[c] = f.name
    for chunk, term in top_level_chunks(strip(raw)):
        if not chunk or re.match(r"(static|extern|typedef|struct\s+\w+\s*$)", chunk):
            continue
        if re.search(r"\b(static|extern|typedef)\b", chunk.split("iosrt_")[0] if "iosrt_" in chunk else chunk):
            continue
        m = re.search(r"\biosrt_([A-Za-z_]\w*)\s*\(", chunk)
        if m and term == "{" and chunk.endswith(")"):
            funcs[m.group(1)] = f.name; continue
        if term == ";" and m and chunk.index(m.group(0)) < (chunk.index("=") if "=" in chunk else len(chunk)):
            continue   # prototype
        decl = chunk.split("=")[0] if "=" not in chunk or "," not in chunk else chunk
        for name in re.findall(r"\biosrt_([A-Za-z_]\w*)\b(?!\s*\()", chunk):
            data[name] = f.name

lines = ["/* UIKit, CoreGraphics, QuartzCore and CoreText exports.",
         " * Generated by tools/gen_uikit_def.py from runtime/src/uikit (all .c files) - do not edit by hand. */"]
for c in sorted(classes):
    lines.append("CLASS(%s, %s)" % ("QuartzCore" if c.startswith("CA") else "UIKit", c))
for n in sorted(funcs):
    if n in data: continue
    lines.append("SYM(%s, _%s, iosrt_%s)" % (lib_for(n), n, n))
for n in sorted(data):
    lines.append("SYM(%s, _%s, &iosrt_%s)" % (lib_for(n), n, n))
out.write_text("\n".join(lines) + "\n")
print("uikit.def: %d classes, %d functions, %d data" % (len(classes), len(funcs), len(data)))
